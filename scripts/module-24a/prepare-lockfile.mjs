import { access, readFile } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import path from 'node:path';
import process from 'node:process';

const lockfilePath = path.resolve('package-lock.json');

/** Return true when the root package-lock already exists. */
async function lockfileExists() {
  try {
    await access(lockfilePath);
    return true;
  } catch {
    return false;
  }
}

/** Run one command with inherited stdio and reject on any non-zero exit. */
function run(command, args) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, { stdio: 'inherit', shell: process.platform === 'win32' });
    child.on('error', reject);
    child.on('exit', (code, signal) => {
      if (code === 0) resolve();
      else reject(new Error(`${command} ${args.join(' ')} failed with ${signal ? `signal ${signal}` : `exit code ${code}`}.`));
    });
  });
}

/** Verify the generated lockfile is modern and describes the current root workspace manifest. */
async function verifyLockfile() {
  const [manifest, lockfile] = await Promise.all([
    readFile('package.json', 'utf8').then(JSON.parse),
    readFile(lockfilePath, 'utf8').then(JSON.parse),
  ]);

  if (!Number.isInteger(lockfile.lockfileVersion) || lockfile.lockfileVersion < 2) {
    throw new Error('Module 24A live acceptance requires package-lock.json lockfileVersion 2 or newer. Regenerate it with the repository npm version.');
  }
  if (!lockfile.packages || typeof lockfile.packages !== 'object' || !lockfile.packages['']) {
    throw new Error('package-lock.json must contain the root packages entry generated by modern npm.');
  }

  const root = lockfile.packages[''];
  for (const field of ['dependencies', 'devDependencies']) {
    const expected = manifest[field] ?? {};
    const actual = root[field] ?? {};
    for (const [name, spec] of Object.entries(expected)) {
      if (actual[name] !== spec) {
        throw new Error(`package-lock.json is out of sync for ${field}.${name}; expected ${spec}, received ${actual[name] ?? '<missing>'}.`);
      }
    }
  }

  const expectedWorkspaces = JSON.stringify(manifest.workspaces ?? []);
  const actualWorkspaces = JSON.stringify(root.workspaces ?? []);
  if (expectedWorkspaces !== actualWorkspaces) {
    throw new Error('package-lock.json workspace declarations are out of sync with package.json.');
  }
}

const existed = await lockfileExists();
if (existed && process.env.MODULE_24A_LOCKFILE_REFRESH !== '1') {
  console.log('package-lock.json already exists; keeping the reviewed lockfile. Set MODULE_24A_LOCKFILE_REFRESH=1 to regenerate it intentionally.');
  await verifyLockfile();
  process.exit(0);
}

console.log(existed ? 'Regenerating the reviewed package-lock.json for Module 24A live acceptance...' : 'Generating package-lock.json for Module 24A live acceptance...');
await run('npm', ['install', '--package-lock-only', '--ignore-scripts', '--no-audit', '--no-fund']);
await verifyLockfile();
console.log('Module 24A package-lock.json is present, modern and synchronized with the root workspace manifest.');
